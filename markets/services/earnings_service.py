def get_upcoming_earnings(limit=None):
    """Return list of upcoming corporate earnings dates."""
    if limit:
        return UPCOMING_EARNINGS[:limit]
    return UPCOMING_EARNINGS

def get_reported_filings(regulator=None, limit=None):
    """Return list of reported statutory earnings filings with optional regulator filter."""
    filings = REPORTED_REGULATORY_FILINGS
    if regulator and regulator.lower() != 'all':
        reg_clean = regulator.lower().strip()
        filings = [f for f in filings if reg_clean in f.get('regulator_code', '').lower() or reg_clean in f.get('regulator', '').lower()]
    if limit:
        return filings[:limit]
    return filings

def get_filing_by_id(filing_id):
    """Retrieve full details for an individual regulatory earnings filing."""
    target = str(filing_id).strip().lower()
    for f in REPORTED_REGULATORY_FILINGS:
        if f['id'].lower() == target:
            return f
    # Also check upcoming earnings by id
    for u in UPCOMING_EARNINGS:
        if u['id'].lower() == target:
            return u
    return None

